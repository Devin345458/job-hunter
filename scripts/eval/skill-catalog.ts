type Plan = Awaited<ReturnType<typeof sc.bootstrapCatalog>>
const subjects = new Map<number, string>(db.select({ id: questions.id, subject: questions.subject }).from(questions).all().map((r: any) => [r.id, r.subject]))
const cell = (s: unknown) => String(s ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim()
/** Model reasons cite prompt ids ("S2", "P14", "Q161"); the report names them instead. */
const plain = (s: unknown) => cell(s)
  .replace(/\bS1\b/g, '"Using AI for supervised coding"')
  .replace(/\bS2\b/g, '"Using AI in unsupervised processes"')
  .replace(/\bS\d+\b/g, 'an existing skill')
  .replace(/\bP\d+\b/g, 'another proposed skill')
  .replace(/\b[QR](\d+)\b/g, '#$1')

function entryMap(plan: Plan): Map<number, string> {
  const map = new Map<number, string>()
  for (const e of plan.entries) for (const m of e.members) map.set(m.id, e.name)
  return map
}

/** The hard key: groups together (and apart from each other), pairs apart. The open tier is listed. */
function score(plan: Plan) {
  const of = entryMap(plan)
  const misses: string[] = []
  let total = 0
  let passed = 0
  const groupNames: string[] = []
  for (const g of KEY.hard.together) {
    const names = g.ids.map((id: number) => of.get(id) ?? '(no skill)')
    const counts = new Map<string, number>()
    for (const n of names) counts.set(n, (counts.get(n) ?? 0) + 1)
    const main = [...counts].sort((a, b) => b[1] - a[1])[0]![0]
    groupNames.push(main)
    g.ids.forEach((id: number, i: number) => {
      total++
      if (names[i] === main) passed++
      else misses.push(`together "${g.label}": #${id} ${subjects.get(id)} is under "${names[i]}", not "${main}"`)
    })
  }
  groupNames.forEach((n, i) => groupNames.forEach((o, j) => {
    if (j > i && n === o) misses.push(`together "${KEY.hard.together[i].label}" and "${KEY.hard.together[j].label}" share the skill "${n}"`)
  }))
  for (const a of KEY.hard.apart) {
    const mine = of.get(a.ids[0])
    for (const id of a.not) {
      total++
      if (mine && of.get(id) === mine) misses.push(`apart "${a.label}": #${id} ${subjects.get(id)} is under "${mine}" with #${a.ids[0]}`)
      else passed++
    }
  }
  const open = KEY.open.map((o: any) => ({ label: o.label, placed: o.ids.map((id: number) => `#${id} ${subjects.get(id)} -> ${of.get(id) ?? '(no skill)'}`) }))
  const inKey = new Set<number>(KEY.hard.together.flatMap((g: any) => g.ids))
  const extras = plan.entries.filter(e => e.members.length > 1 && !e.members.every(m => inKey.has(m.id)))
    .map(e => `${e.name}: ${e.members.map(m => `#${m.id} ${m.subject}`).join(', ')}`)
  return { passed, total, misses, open, extras }
}

function callStats(sinceId: number) {
  const rows = db.select().from(aiCalls).where(gt(aiCalls.id, sinceId)).all()
  const by: Record<string, { calls: number; estUsd: number; errors: string[]; model: string }> = {}
  for (const r of rows) {
    const s = by[r.purpose] ??= { calls: 0, estUsd: 0, errors: [], model: r.model }
    s.calls++
    s.estUsd += r.estCostUsd ?? 0
    if (r.error) s.errors.push(r.error.slice(0, 160))
  }
  return by
}

