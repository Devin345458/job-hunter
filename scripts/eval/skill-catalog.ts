if (mode === 'bootstrap') {
  const before = lastCallId()
  const times: Record<string, number[]> = { distill: [], review: [] }
  const t0 = Date.now()
  const reuse = flag('drafts')
  const plan = await sc.bootstrapCatalog({
    distillModel,
    reviewModel,
    log: m => console.log(m),
    onCall: (step, s) => times[step]!.push(s),
    drafts: reuse ? JSON.parse(readFileSync(reuse, 'utf8')) : undefined,
    onDrafts: d => writeFileSync(join(outDir!, `${label}-drafts.json`), JSON.stringify(d, null, 2)),
  })
  const seconds = (Date.now() - t0) / 1000
  const stats = callStats(before)
  if (plan.error) {
    console.error(`bootstrap failed: ${plan.error}`)
    writeFileSync(join(outDir!, `${label}-error.json`), JSON.stringify({ error: plan.error, stats }, null, 2))
    process.exit(1)
  }
  const s = score(plan)
  const perStep = Object.fromEntries(Object.entries(stats).map(([p, v]) => [p, { ...v, estUsdPerCall: v.estUsd / v.calls, avgSeconds: (p === sc.DISTILL_PURPOSE ? times.distill : times.review).reduce((a, b) => a + b, 0) / Math.max(1, (p === sc.DISTILL_PURPOSE ? times.distill : times.review).length) }]))
  writeFileSync(join(outDir!, `${label}-plan.json`), JSON.stringify(plan, null, 2))
  writeFileSync(join(outDir!, `${label}-score.json`), JSON.stringify({ label, distillModel, reviewModel, seconds, perStep, ...s }, null, 2))
  writeFileSync(join(outDir!, `${label}-catalog.md`), catalogReport(plan, s))
  console.log(`\n${label}: hard key ${s.passed}/${s.total} in ${seconds.toFixed(0)} s; ${plan.entries.length} skills`)
  for (const [p, v] of Object.entries(perStep)) console.log(`  ${p}: ${v.calls} calls on ${v.model}, est. $${v.estUsd.toFixed(3)} ($${v.estUsdPerCall.toFixed(4)} a call), ${v.avgSeconds.toFixed(1)} s a call${v.errors.length ? `, errors: ${v.errors.join(' | ')}` : ''}`)
  for (const m of s.misses) console.log(`  MISS ${m}`)
  console.log('  open tier:')
  for (const o of s.open) console.log(`    ${o.label}: ${o.placed.join('; ')}`)
  console.log(`  report: ${join(resolve(outDir!), `${label}-catalog.md`)}`)
}

if (mode === 'cases') {
  const plan: Plan = JSON.parse(readFileSync(flag('plan')!, 'utf8'))
  sc.applyCatalogPlan(plan)
  const of = entryMap(plan)
  const results: any[] = []
  for (const c of KEY.cases) {
    const question = c.question ?? (c.kind === 'knows' ? `Have you used ${c.subject} in a real project?` : `Have you done ${c.subject}?`)
    const before = lastCallId()
    const t = Date.now()
    const r = await sc.distillSkills([{ subject: c.subject, kind: c.kind, question, phrase: c.posting, context: `Acme asks for: ${c.posting}. The knowledge base does not say whether you have this.` }])
    const seconds = (Date.now() - t) / 1000
    const stats = callStats(before)
    const match = sc.skillMatch(c.subject)
    let skill = match.decided ? match.entry.name : null
    let how = r.decided[0] ? (r.decided[0].created ? 'new skill' : 'mapped') : 'no call'
    if (!skill) {
      const exact = q.exactQuestionFor(c.kind, c.subject)
      skill = exact ? (sc.loadCatalog().find(e => e.questionId === exact.id)?.name ?? `question #${exact.id}`) : '(none)'
      how = r.error ? `failed: ${r.error.slice(0, 80)}` : 'exact check'
    }
    const want = c.with != null ? of.get(c.with) ?? null : null
    const nots = (c.not ?? []).map((id: number) => of.get(id)).filter(Boolean)
    const ok = (want == null || skill === want) && !nots.includes(skill)
    results.push({ subject: c.subject, skill, how, ok, want, not: nots, reason: r.decided[0]?.reason ?? null, seconds, stats })
    console.log(`${ok ? 'ok  ' : 'MISS'} ${c.subject} -> ${skill} (${how}, ${seconds.toFixed(1)} s)${ok ? '' : ` want ${want ? `"${want}"` : `not ${nots.map((n: string) => `"${n}"`).join(', ')}`}`}`)
  }
  const passed = results.filter(r => r.ok).length
  const per: Record<string, { calls: number; estUsd: number }> = {}
  for (const r of results) for (const [p, v] of Object.entries(r.stats as Record<string, any>)) {
    const s = per[p] ??= { calls: 0, estUsd: 0 }
    s.calls += v.calls
    s.estUsd += v.estUsd
  }
  const called = results.filter(r => r.how === 'mapped' || r.how === 'new skill')
  const summary = { label, distillModel, reviewModel, passed, total: results.length, avgSeconds: called.reduce((a, r) => a + r.seconds, 0) / Math.max(1, called.length), perPurpose: Object.fromEntries(Object.entries(per).map(([p, v]) => [p, { ...v, estUsdPerCall: v.estUsd / v.calls }])), results }
  writeFileSync(join(outDir!, `${label}-cases.json`), JSON.stringify(summary, null, 2))
  console.log(`\n${label}: cases ${passed}/${results.length}; ${summary.avgSeconds.toFixed(1)} s a case; ${Object.entries(summary.perPurpose).map(([p, v]) => `${p} ${v.calls} calls est. $${v.estUsdPerCall.toFixed(4)} a call`).join('; ')}`)
}

function normalize(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9+#]+/g, ' ').trim()
}

/** The catalog report Devin reviews before anything applies in production. */
function catalogReport(plan: Plan, s: ReturnType<typeof score>): string {
  const lines: string[] = []
  const multi = plan.entries.filter(e => e.members.length > 1)
  const single = plan.entries.filter(e => e.members.length <= 1)
  const merges = plan.entries.flatMap(e => e.members.filter(m => m.action === 'merge'))
  const rewords = plan.entries.filter(e => e.reword)
  lines.push('# Skill catalog (proposed)', '')
  lines.push(`${plan.name}. Distill model ${plan.models.distill}, review model ${plan.models.review}. Nothing here applies in production until Devin approves it; production then applies this list by id, once, and skips any question that changed since.`, '')
  lines.push(`- ${plan.entries.length} skills from ${plan.candidates} open, answered, and app-skipped skill and experience questions.`)
  lines.push(`- ${multi.length} skills hold more than one question; ${single.length} hold one.`)
  lines.push(`- ${merges.length} questions would merge into their skill's question (status skipped, note "Merged into question #N").`)
  const renamed = rewords.filter(e => normalize(e.members.find(m => m.id === e.canonicalId)?.subject ?? '') !== normalize(e.name))
  lines.push(`- ${rewords.length} open questions would be reworded to their skill's generic question; ${renamed.length} of them also take a new subject (the skill name), and their knowledge base key follows it. Answered questions keep their wording. Your call: reword all of them, only the ${multi.filter(e => e.reword).length} skills with more than one question, or none.`)
  lines.push(`- ${plan.entries.filter(e => e.conflict).length} skills hold two answers of yours that differ; nothing in them merges.`)
  lines.push(`- Answer key: ${s.passed} of ${s.total} hard checks pass.`, '')

  // Core suggestions: many postings ask, and his records are strong.
  lines.push('## Suggested core skills', '')
  lines.push('A core skill would get a full answer; every other skill 2 or 3 sentences. Suggested where many postings ask and your records are strong. The flag is stored as false for every skill until you set it.', '')
  const suggestions = plan.entries.map((e) => {
    const ids = e.members.map(m => m.id)
    const rows = ids.length ? db.select().from(questions).where(inArray(questions.id, ids)).all() : []
    const asks = rows.reduce((n: number, r: any) => n + Number((r.context ?? '').match(/(\d+) open jobs ask/)?.[1] ?? 1), 0)
    const yes = e.members.filter(m => m.status === 'answered' && /^(yes|some)/i.test(m.answer ?? ''))
    const repo = ids.length ? db.select().from(repoSuggestions).where(inArray(repoSuggestions.questionId, ids)).all().filter((r: any) => r.status === 'suggested') : []
    const kb = q.knowledgeCovers(e.name)
    const records = [
      yes.length ? `you answered ${yes.map(m => `#${m.id} ${m.answer}`).join(', ')}` : '',
      repo.length ? `your GitHub suggests ${repo.length === 1 ? 'an answer' : `${repo.length} answers`}` : '',
      kb && !q.isNegativeKnowledge(kb.value) ? `your knowledge base has ${kb.category}: ${kb.key}` : '',
    ].filter(Boolean)
    return { e, asks, records }
  }).filter(x => x.asks >= 4 && x.records.length).sort((a, b) => b.asks - a.asks)
  if (!suggestions.length) lines.push('None meet both tests (4 or more postings, and an answer or evidence of yours).')
  for (const x of suggestions) lines.push(`- **${x.e.name}:** asked by about ${x.asks} postings; ${x.records.join('; ')}.`)

  lines.push('', '## Where the open questions landed', '')
  for (const e of plan.entries) {
    for (const o of KEY.open) {
      const here = e.members.filter(m => o.ids.includes(m.id))
      for (const m of here) lines.push(`- ${cell(o.label)}: #${m.id} ${cell(m.subject)} is under **${cell(e.name)}**. Why: ${plain(m.why)}`)
    }
  }
  if (s.misses.length) {
    lines.push('', '## Answer key misses', '')
    for (const m of s.misses) lines.push(`- ${cell(m)}`)
  }
  if (plan.review.length) {
    lines.push('', '## What the review changed', '')
    for (const r of plan.review) lines.push(`- ${cell(r.what)}: ${plain(r.reason)}`)
  }
  lines.push('', '## Skills with more than one question', '')
  for (const e of multi) {
    lines.push(`### ${cell(e.name)} (${e.kind === 'knows' ? 'skill' : 'experience'})`, '')
    lines.push(`Question: "${cell(e.question)}"`, '')
    lines.push(`Scope: ${cell(e.scope)}`, '')
    lines.push(`Canonical: ${e.canonicalId != null ? `#${e.canonicalId}${e.reword ? ' (reworded to the generic question)' : ''}` : 'none'}. Answer it keeps: ${e.answerFrom ? `#${e.answerFrom.id} "${cell(e.answerFrom.answer)}"` : 'none yet'}.${e.conflict ? ` Left alone: ${cell(e.conflict)}.` : ''}`, '')
    lines.push('| Id | Subject | Status | Action | Posting |', '|---|---|---|---|---|')
    for (const m of e.members) lines.push(`| #${m.id} | ${cell(m.subject)} | ${m.status === 'answered' ? `answered ${cell(m.answer)}` : m.status === 'skipped' ? 'skipped by the app' : 'open'} | ${m.action === 'canonical' ? 'the one to answer' : m.action === 'merge' ? `merge into #${e.canonicalId}` : `keep: ${cell(m.reason)}`} | ${cell(m.posting)} |`)
    lines.push('')
  }
  lines.push('## Skills with one question', '')
  lines.push('A reworded question takes the skill name as its subject and the generic question as its wording; when the name differs from the subject, its knowledge base key moves to the skill name too.', '')
  lines.push('| Id | Subject now | Skill | Reworded to |', '|---|---|---|---|')
  for (const e of single) {
    for (const m of e.members) lines.push(`| #${m.id} | ${cell(m.subject)} | ${cell(e.name)}${normalize(m.subject) !== normalize(e.name) ? ' (renamed)' : ''} | ${e.reword ? `"${cell(e.question)}"` : 'kept'} |`)
    if (!e.members.length) lines.push(`| none | (no question yet) | ${cell(e.name)} | no |`)
  }
  return `${lines.join('\n')}\n`
}
